def ist_now():
    return dt.datetime.now(dt.timezone.utc) + dt.timedelta(hours=5, minutes=30)


def lesson_today(now=None):
    now = now or ist_now()
    n = (now.date() - dt.date(1970, 1, 1)).days      # website ke dayNum jaisa (IST din)
    return LESSONS[n % len(LESSONS)]


def build(rows, events, fg, now=None):
    """rows: [(emoji, name, price_text, chg24, st)], events: news_alert.load_events() suchi."""
    now = now or ist_now()
    wk = now.weekday()
    head = f"🌅 सुबह का सारांश\n📆 {DAYS[wk]}, {now.day} {MONTHS[now.month - 1]}\n\n"
    lines = []
    for emoji, name, ptxt, chg, st in rows:
        lines.append(f"{emoji} {name}  {ptxt}  (24घं {chg:+.2f}%)  | बड़ा ट्रेंड: {ICON.get(st, '')}")
    body = "📊 बाज़ार का हाल (24 घंटे)\n" + "\n".join(lines) + "\n"
    if wk >= 5:
        body += "ℹ️ शनिवार-रविवार को सोना, EUR/USD और Nasdaq बंद रहते हैं।\n"
    if fg:
        body += f"\n😨 डर/लालच सूचकांक: {fg[0]} ({FG_HI.get(fg[1], fg[1])})\n"
    today = now.date()
    todays = sorted([e for e in (events or []) if A.ist(e["t"]).date() == today], key=lambda e: e["t"])
    body += "\n📅 आज की बड़ी खबरें (भारत समय)\n"
    if todays:
        for e in todays[:6]:
            body += f"• {A.ist(e['t']).strftime('%I:%M %p')} — {e['cur']}: {e['title']}\n"
        body += "🔔 हर खबर से 10 मिनट पहले हम यहीं अलर्ट भेजेंगे।\n"
    else:
        body += "आज कोई तय बड़ी खबर नहीं है।\n"
    t, b = lesson_today(now)
    body += f"\n📘 आज की सीख: {t}\n{b}\n"
    body += f"\n👉 रोज़ की सीख और स्ट्रीक: {SITE}\n⚠️ सिर्फ़ पढ़ाई के लिए, खरीदने-बेचने की सलाह नहीं।"
    return (head + body)[:4000]
